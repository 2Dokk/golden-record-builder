WEIGHTS = (1, 3, 7, 1, 3, 7, 1, 3, 5)


def with_check_digit(first9: str) -> str:
    d = [int(c) for c in first9]
    total = sum(x * w for x, w in zip(d, WEIGHTS)) + (d[8] * 5) // 10
    return first9 + str((10 - total % 10) % 10)


def hyphen(d: str) -> str:
    return f"{d[:3]}-{d[3:5]}-{d[5:]}"


def broken_check_digit(first9: str) -> str:
    valid = with_check_digit(first9)
    return valid[:9] + str((int(valid[9]) + 1) % 10)


